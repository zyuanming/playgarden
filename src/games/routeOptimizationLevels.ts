import type { RouteLevel } from "./routeOptimizationLogic";

/** Twelve individually authored weighted maps per game. Certificates are literal walks, never used to pick UI moves. */
function level(
  id: string,
  mode: RouteLevel["mode"],
  title: string,
  points: readonly (readonly [number, number])[],
  roads: readonly (readonly [number, number, number])[],
  idea: string,
  difficulty: RouteLevel["difficulty"],
  decision: string,
  walk: readonly number[],
  minimumCost: number,
): RouteLevel {
  return {
    id,
    mode,
    title,
    depot: 0,
    idea,
    difficulty,
    decision,
    towns: points.map(([x, y], i) => ({
      x,
      y,
      label: String.fromCharCode(65 + i),
    })),
    roads: roads.map(([a, b, cost]) => ({ a, b, cost })),
    certificate: { schema: "playgarden.route.v1", walk, minimumCost },
  };
}

