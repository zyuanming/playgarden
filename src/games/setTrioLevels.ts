// Original authored layouts. Digits are color, shape, count-minus-one, fill.
// Each written row is a constructive partition, NOT the only accepted answer.
// Boards interleave rows for display; no board is a shuffle of another lesson.
export type TrioValue = 0 | 1 | 2;
export type TrioCard = readonly [TrioValue, TrioValue, TrioValue, TrioValue];
export type TrioLevel = {
  id: string;
  title: string;
  chapter: string;
  lesson: string;
  cards: TrioCard[];
};
function authored(
  id: string,
  title: string,
  chapter: string,
  lesson: string,
  rows: readonly (readonly [string, string, string])[],
): TrioLevel {
  const codes = [0, 1, 2].flatMap((column) => rows.map((row) => row[column]));
  return {
    id, title, chapter, lesson,
    cards: codes.map((code) => code.split('').map(Number) as unknown as TrioCard),
  };
}
